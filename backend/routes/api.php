<?php

use App\Http\Controllers\Api\AuthController;
use App\Http\Controllers\Api\AccountController;
use App\Http\Controllers\Api\ChatController;
use App\Http\Controllers\Api\DashboardController;
use App\Http\Controllers\Api\DrugController;
use App\Http\Controllers\Api\InventoryController;
use App\Http\Controllers\Api\PatientController;
use App\Http\Controllers\Api\PharmacySettingController;
use App\Http\Controllers\Api\PrescriptionController;
use App\Http\Controllers\Api\SaleController;
use App\Http\Controllers\Api\SyncConflictController;
use App\Http\Controllers\Api\SupplierController;
use App\Http\Controllers\Api\StockCountController;
use App\Http\Controllers\Api\UserController;
use Illuminate\Support\Facades\Route;

Route::post('/auth/login', [AuthController::class, 'login'])->middleware('throttle:10,1');
Route::get('/desktop-discovery', [StockCountController::class, 'discovery']);
Route::middleware('auth:sanctum')->group(function () {
    Route::post('/auth/logout', [AuthController::class, 'logout']);
    Route::get('/me', [AuthController::class, 'me']);
    Route::patch('/account/profile', [AccountController::class, 'update']);
    Route::get('/chat/contacts', [ChatController::class, 'contacts']);
    Route::get('/chat/{user}/messages', [ChatController::class, 'messages']);
    Route::post('/chat/{user}/messages', [ChatController::class, 'send'])->middleware('throttle:60,1');
    Route::post('/sync/sales', [SaleController::class, 'sync'])->middleware('role:hod,pharmacy_staff');
    Route::get('/prescriptions', [PrescriptionController::class, 'index'])->middleware('role:hod,doctor,pharmacy_staff');
    Route::post('/prescriptions', [PrescriptionController::class, 'store'])->middleware('role:hod,doctor');
    Route::get('/prescriptions/{prescription}', [PrescriptionController::class, 'show'])->middleware('role:hod,doctor,pharmacy_staff');
    Route::get('/settings/alerts', [PharmacySettingController::class, 'show'])->middleware('role:hod');
    Route::put('/settings/alerts', [PharmacySettingController::class, 'update'])->middleware('role:hod');
    Route::get('/sync/conflicts', [SyncConflictController::class, 'index'])->middleware('role:hod');
    Route::patch('/sync/conflicts/{syncConflict}/review', [SyncConflictController::class, 'review'])->middleware('role:hod');
    Route::get('/sales', [SaleController::class, 'index'])->middleware('role:hod,md,pharmacy_staff');
    Route::get('/dashboard', [DashboardController::class, 'index'])->middleware('role:hod,md');
    Route::get('/reports', [DashboardController::class, 'reports'])->middleware('role:hod,md');
    Route::get('/drugs', [DrugController::class, 'index'])->middleware('role:hod,store_keeper,pharmacy_staff,md,doctor');
    Route::get('/drugs/{drug}', [DrugController::class, 'show'])->middleware('role:hod,store_keeper,pharmacy_staff,md,doctor');
    Route::post('/drugs', [DrugController::class, 'store'])->middleware('role:hod');
    Route::match(['put','patch'], '/drugs/{drug}', [DrugController::class, 'update'])->middleware('role:hod');
    Route::delete('/drugs/{drug}', [DrugController::class, 'destroy'])->middleware('role:hod');
    Route::apiResource('users', UserController::class)->middleware('role:hod');
    Route::get('/patients', [PatientController::class, 'index'])->middleware('role:hod,pharmacy_staff,doctor');
    Route::get('/patients/{patient}', [PatientController::class, 'show'])->middleware('role:hod,pharmacy_staff,doctor');
    Route::post('/patients', [PatientController::class, 'store'])->middleware('role:hod,pharmacy_staff');
    Route::match(['put','patch'], '/patients/{patient}', [PatientController::class, 'update'])->middleware('role:hod,pharmacy_staff');
    Route::delete('/patients/{patient}', [PatientController::class, 'destroy'])->middleware('role:hod');
    Route::get('/inventory', [InventoryController::class, 'index'])->middleware('role:hod,store_keeper,pharmacy_staff,md');
    Route::get('/inventory/summary', [InventoryController::class, 'summary'])->middleware('role:hod,store_keeper,pharmacy_staff,md');
    Route::post('/inventory/stock', [InventoryController::class, 'store'])->middleware('role:hod,store_keeper');
    Route::post('/inventory/transfers', [InventoryController::class, 'transfer'])->middleware('role:hod,store_keeper');
    Route::get('/inventory/transfers', [InventoryController::class, 'transfers'])->middleware('role:hod,store_keeper');
    Route::get('/stock-counts/active', [StockCountController::class, 'active'])->middleware('role:hod,store_keeper,pharmacy_staff');
    Route::get('/stock-counts', [StockCountController::class, 'index'])->middleware('role:hod,store_keeper,pharmacy_staff');
    Route::post('/stock-counts', [StockCountController::class, 'start'])->middleware('role:hod,store_keeper');
    Route::get('/stock-counts/{stockCount}', [StockCountController::class, 'show'])->middleware('role:hod,store_keeper,pharmacy_staff');
    Route::put('/stock-counts/{stockCount}/items/{item}', [StockCountController::class, 'record'])->middleware('role:hod,store_keeper,pharmacy_staff');
    Route::post('/stock-counts/{stockCount}/complete', [StockCountController::class, 'complete'])->middleware('role:hod');
    Route::apiResource('suppliers', SupplierController::class)->middleware('role:hod,store_keeper');
    Route::get('/departments', [InventoryController::class, 'departments'])->middleware('role:hod,store_keeper,pharmacy_staff,md');
});
